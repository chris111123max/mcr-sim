#!/usr/bin/env python3
"""TEST ONLY: evaluate the 3x native relinearization × 1e-9 tolerance branch.

Reads independent NPZ/JSON captures, never modifies SOFA, production or training.
The branch MUST be generated by the pre-existing test-only native replay harness;
the checker does not claim that JSON flags prove native solves occurred.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
from scipy.spatial.transform import Rotation

TARGET_MM = 0.100
BASELINE_MM = 0.082681
TRIPLE_MM = 0.096711
PREFIX_HASH = "6f534ad5155bfa635666f9d3237783681e65dc378a3d5608706db30bb00e181c"

def read_npz(path):
    with np.load(path, allow_pickle=False) as d:
        return {k:d[k].copy() for k in d.files}

def arr(d, *names):
    for name in names:
        if name in d:
            x=np.asarray(d[name])
            if not np.issubdtype(x.dtype,np.number) or not np.isfinite(x).all():
                raise ValueError(f"Non-numeric/nonfinite {name}")
            return x
    raise ValueError("Missing: "+"/".join(names))

def scalar(d,*names):
    return float(arr(d,*names).reshape(-1)[0])

def state_delta(a,b):
    if a.shape!=b.shape or a.ndim!=2 or a.shape[1]!=7:
        raise ValueError("invalid (N,7) Rigid3")
    shift=float(np.max(np.abs(a[:,:3]-b[:,:3])))
    ra=Rotation.from_quat(a[:,3:7])
    rb=Rotation.from_quat(b[:,3:7])
    angle=float(np.max((rb*ra.inv()).magnitude()))
    return {"max_abs_translation_m":shift,"max_rotation_rad":angle,
            "same":shift<=1e-10 and angle<=1e-10}

def evaluate(d):
    profile=arr(d,"q_committed_dense_clearance","committed_dense_clearance").reshape(-1)
    inds=arr(d,"selected_dense_indices").astype(int).reshape(-1)
    gaps=arr(d,"linear_row_gaps_committed","committed_linear_gaps","row_gaps") .reshape(-1) if any(k in d for k in ("linear_row_gaps_committed","committed_linear_gaps","row_gaps")) else None
    active=int(scalar(d,"activeCount","active_count","native_active_count"))
    rows=int(scalar(d,"rebuild_row_count","row_count","native_row_count"))
    if profile.size==0 or np.any(inds<0) or np.any(inds>=profile.size):
        raise ValueError("invalid independent dense profile/selected indices")
    c=float(np.min(profile))*1000
    return {"min_clearance_mm":c,"margin_shortfall_mm":TARGET_MM-c,
            "meets_0p100mm":bool(c>=TARGET_MM-1e-9),
            "worst_dense_index":int(np.argmin(profile)),
            "worst_point_selected":bool(int(np.argmin(profile)) in set(inds.tolist())),
            "rebuild_rows":rows,"native_activeCount":active,
            "row_activation_valid":active==rows,
            "min_native_linear_gap_mm":None if gaps is None else float(np.min(gaps))*1000,
            "linear_gap_available":gaps is not None}

def provenance(d,meta):
    required=("native_solve_count","mapping_refresh_count","physics_substeps_executed",
              "extra_animate_count","position_overwrite_count","solver_tolerance",
              "action_prefix_sha256","target_rl_step","target_substep")
    missing=[x for x in required if x not in meta]
    if missing:
        return {"status":"INCONCLUSIVE","missing":missing}
    flags={
      "native_solves_3":int(meta["native_solve_count"])==3,
      "mapping_refresh_2":int(meta["mapping_refresh_count"])==2,
      "single_physics_substep":int(meta["physics_substeps_executed"])==1,
      "no_extra_animate":int(meta["extra_animate_count"])==0,
      "no_position_overwrite":int(meta["position_overwrite_count"])==0,
      "tolerance_1e-9":abs(float(meta["solver_tolerance"])-1e-9)<=1e-15,
      "action_prefix_match":str(meta["action_prefix_sha256"])==PREFIX_HASH,
      "step_2009":int(meta["target_rl_step"])==2009,
      "substep_1":int(meta["target_substep"])==1,
    }
    return {"status":"SELF_REPORTED_NATIVE_FLAGS","checks":flags,
            "all_claims_pass":all(flags.values()),
            "warning":"Must audit genuine native trace; metadata alone is not proof of native re-solve."}

def run(args):
    b=read_npz(args.baseline)
    t=read_npz(args.triple)
    j=read_npz(args.joint)
    mb=json.loads(args.joint_meta.read_text(encoding="utf-8"))
    same={
      "baseline_vs_joint_q_prev":state_delta(arr(b,"q_prev"),arr(j,"q_prev")),
      "baseline_vs_joint_q_free":state_delta(arr(b,"q_free"),arr(j,"q_free")),
      "triple_vs_joint_q_prev":state_delta(arr(t,"q_prev"),arr(j,"q_prev")),
      "triple_vs_joint_q_free":state_delta(arr(t,"q_free"),arr(j,"q_free")),
    }
    e={name:evaluate(d) for name,d in (("baseline",b),("triple_original_tolerance",t),("triple_tight_tolerance",j))}
    baseline_ref=abs(e["baseline"]["min_clearance_mm"]-BASELINE_MM)<=5e-5
    triple_ref=abs(e["triple_original_tolerance"]["min_clearance_mm"]-TRIPLE_MM)<=5e-5
    trace=provenance(j,mb)
    comparisons_valid=all(x["same"] for x in same.values()) and baseline_ref and triple_ref and trace.get("all_claims_pass",False) and all(x["row_activation_valid"] for x in e.values())
    outcome="INCONCLUSIVE"
    if comparisons_valid:
        outcome="PASS" if e["triple_tight_tolerance"]["meets_0p100mm"] else "FAIL"
    report={
      "experiment":"3-native-solve relinearization x solver tolerance 1e-9",
      "baseline_match":baseline_ref,"triple_original_match":triple_ref,
      "same_frame":same,"arms":e,
      "native_trace_claims":trace,"comparison_valid_pending_log_audit":comparisons_valid,
      "margin_acceptance":outcome,
      "native_trace_audit":"REQUIRED",
      "original_minus_0p766410143mm_failure_explained":False,
      "production_writes":False,
      "note":"Independent 10um SDF is authoritative for this frozen frame; solver tolerance attainment must be established separately from logged residual with solver-specific semantics."
    }
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
    print(json.dumps(report,ensure_ascii=False,indent=2))
    return 0 if outcome!="INCONCLUSIVE" else 2

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--baseline",type=Path,required=True)
    p.add_argument("--triple",type=Path,required=True,
                   help="Captured 3-native-solve branch at original tolerance")
    p.add_argument("--joint",type=Path,required=True,
                   help="Captured 3-native-solve branch at tolerance 1e-9")
    p.add_argument("--joint-meta",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    try:
        return run(a)
    except (ValueError,KeyError,FileNotFoundError,OSError) as exc:
        print("INCONCLUSIVE: "+str(exc),file=sys.stderr)
        return 2

if __name__=="__main__":
    raise SystemExit(main())
